#include <iostream>
#include <cstdlib>
#include <ctime>
#include <clocale>
using namespace std;
int main()
{
	setlocale(LC_ALL, "RU");
	srand(time(0));
	const int N=100;// максимальный размер массива
	int a[N];//статистический массив
	int n;//длина реального массива(<=100)
	int c;//переменная, значение которой потом удалим из массива

	cout << "введите длину массива: ";
	cin >> n;//вводим длину массива

	for (int i = 0; i < n;++i)
	{
		a[i] = rand() % 41 - 20;//с помощью функции rand() добавляем в массив случайные числа в диапазоне от -20 до 20
		cout << a[i] << ' ';

	}
	
	cout << "\nвведите значение, которое нужно удалить: ";
	cin >> c;

	for (int i = 0;i < n;)//перебираем элементы в массиве
	{
		if (a[i] == c)
		{
			for (int j = i; j < n - 1;++j)//если совпало, то сдвигаем массив влево на 1. в конце остается лишний элемент, который равен предпоследнему
				{
				a[j] = a[j + 1];//текущее значение равно следующему
				}
			n -= 1;//длина массива уменьшилась на 1
		}
		else ++i;
	}
	
	cout << "\nпромежуточный результат: \n";
	for (int i = 0; i < n; i++) 
	{          // печатаем массив после удаления
		cout << a[i] << " ";
	}

	for (int i = 0;i < n;++i)//перебираем элементы массива
	{
		if (a[i] % 2 == 0)//если элемент четный, то сдвигаем элементы начиная с i вправо. начинаем с конца, чтобы не сбить индексы
		{
			for (int j = n; j > i; --j)
				{
				a[j] = a[j - 1];//правый элемент получает значение левого
				}
			a[i] = 0;//кладём новый 0 в освободившееся место
			n++;//длина увеличилась на 1
			i++;//увеличиваем i, чтобы пропустить вставленный 0 и элемен, который мы уже прошли
		}
	}

	cout << "\nИтоговый массив: ";
	for (int i = 0; i < n;++i)
	{
		cout << a[i] << ' ';
	}
	return 0;
}
