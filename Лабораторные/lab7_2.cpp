#include <iostream>
#include <clocale>
using namespace std;

int min(int k, ...) /*функция с переменным числом параметров находит минимум из k чисел типа int.k — обязательный параметр(сколько чисел будет),
дальше может быть любое количество аргументов*/
{
    int* p = &k;//p указывает на k
    int m = *(++p);//передвигаем указатель на следующую ячейку, значение в ней будет начальным минимумом
    for (int i = 1;i < k;++i)//проходим с i=1, так как первое число мы уже прочитали
    {
        int a = *(++p);//опять передвинули указатель и прочитали число
        if (a < m)//если она меньше минимума
            m = a;//то присваиваем это значение минимуму
    }
    return m;//возвращаем минимум
}

int main()
{
    setlocale(LC_ALL, "RU");
    cout << "5 чисел, min= " << min(5, 34, 5, 13, 78, 8) << endl;
    cout << "10 чисел, min= " << min(10, 75, 3, -44, 12, -9, 7, 31, 87, 15, 21) << endl;
    cout << "12 чисел, min= " << min(12, 7, 32, 58, -8, 76, 11, 29, 3, 18, -10, -23, 9) << endl;
    return 0;
}
